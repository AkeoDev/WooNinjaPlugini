    <h2>1. korak - Prijava</h2>
    <p>V prvem koraku pod zavihkom miniMax v vašem WooCommerce nastavite 
    svoj profil. Med opravljanjem postopka vam je ves čas na voljo naša hitra 
    pomoč, v zelenem kvadratu na desni strani. Nastaviti morate uporabniško ime in geslo. 
    Uporabniški račun je potrebno nastaviti v <a href="https://login.saop.si/Profile" target='_BLANK'>SAOP uporabniškem računu</a>
    v poglavju <b>GESLA ZA DOSTOP ZUNANJIH APLIKACIJ</b> (na dnu strani) kliknite na gumb <b>NOVA APLIKACIJA.</b>
    Pravilni podatki za povezovanje v MiniMax so ključni, saj vam v nasprotnem primeru ne bo delovalo.</p>

<hr>
<h2>2. korak - Obvezne nastavitve</h2>
<b>Obvezni podatki:</b>
<ul>
    <li>
        Izberite organizacijo
    </li>
    <li>
        Blagajnik (v kolikor imate dodano Elektronsko napravo za gotovinsko plačevanje). Blagajnik mora imeti vnešeno tudi davčno številko v Minimax računu.
    </li>
    <li>
        Izpis - izdani računi
    </li>
    <li>
        Izpis - Dobavnica (v primeru, da je ne uporabljate, je to kljub temu <b>obvezen podatek</b>)
    </li>
    <li>
        Plačilne metode. Pri tem je potrebno povezati plačilne metode, ki jih uporabljate v Woocommercu in s plačilnimi metodami, ki so v uporabi v Minimax računu. 
        <i>Kartica je smatra kot gotovinsko plačevanje, zato je ptorebno nastavitve temu primerno nastaviti. V tem primeru bo potreben Blagajnik. Lahko pa Kartico nastavite kot transakcijski račun. </i>
    </li>
</ul>
V kolikot imate spustne sezname prazne, lahko preverite v vašem MiniMax prodilu ali imate nastavitve pravilno nastavljene. 
Če je tam pravilno nastavljeno je lahko vrzrok tudi v tem, da niste pravilno povezani z Mnimax modulom in vašem profilom. </p>
<hr>
<h2>3. korak - Izdelki</h2>
<p>
    Vtičnik omogoča preverjanje preko <b>SKU-ja</b>. Če imate v Minimax računu artikle že vnešene, predlagamo, da izberite možnost <b>Preverjanje artiklov preko SKU</b> in nato v Minimax računu pri šifri artikla SKU dodate. <br>
    Na ta način se boste izognili podvajanju izdelkov. <br>
    V primeru, da artiklov v Minimax še nimate, lahko to polje pustite odkljukano, saj bo vtičnik pri izdanem računu artijel samodejno dodal v Minimax in pri tem pripisal unikatno šifro. 
</p>
<h2>4. korak - Elektronska pošta</h2>
<p>V tretjem koraku nastavite privzeto elektronsko pošto, ki jo bo sistem, 
skupaj z računom, poslal stranki po opravljenem nakupu v vaši spletni 
trgovini. Vsebino sporočila lahko popolnoma prilagodite in personalizirate. <br>
Za avtomatsko prikazovanje imena, priimka ali številke naročila, lahko uporabite značke: <b>[orderid]</b> | <b>[name]</b> | <b>[surname]</b><br>
Večjezične spletne trgovine tudi jezik pisanja prilagodite glede na stranke. 
</p>
<hr>
<h2>5. korak - Naročila in izdajanje računov</h2>
<p>
Ko je vaš profil nastavljen lahko dostopate do seznama naročil (orders), na katerem
s pomočjo filtra pregledujete že izdane in čakajoče račune. Če je račun že bil izdan, se bo pri naročilu prikazal <b>Izdani račun</b><br>
Pri vsakem naročilu lahko pod zavihkom MiniMax izdajate in urejate račun. <br>
Kadar se račun izda, se skupaj z računom v MiniMax doda stranka in izdelki.<br>
Če po izdanem računu spreminjate podatke plačnika, lahko s klikom na <b>Posodobi stranko</b>, vrednosti spremenite tudi v vašem Minimax profilu. 
</p>
<h2>6. korak - Posodabljanje izdelka</h2>
<p>
    Skupaj z izdanim računom ze v MiniMax doda artikel (4.korak). Kadar izdelku spremenite ime ali ceno, lahko podatke posodobite na posameznem izdelku s klikom na <b>Posodobi izdelek</b>
</p>
